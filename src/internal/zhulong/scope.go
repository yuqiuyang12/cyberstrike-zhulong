package zhulong

// ScopeBoundary 是烛龙/昭衡统一的「写操作边界」——只保留四条底线。
//
// 口径来源（2026-11-04 用户裁定）：
//
//	「我说它的 w 表有吗, 没有的话就加个只保留四条底线
//	 （禁可用性打击、禁销毁他人数据、禁真金/真人不可逆、不越范围）这个就行了」
//
// 与平台全局 EngagementLatitudeSection（软提示）的区别：
//   - 全局软提示对全部模式生效，只有一句"影响真实人员/资金或不可恢复时先确认"；
//   - 本节只注入烛龙（以及复用同一 kernel 的昭衡），把「唯一需要人拍板的事」写成显式四条，
//     其余写操作（含自建对象上的建/改/删、状态机验证）不再需要报备。
//
// 修改本常量即对 zhulong 全部轮次生效（每轮作为系统提示追加），无需改 roles/config。
const ScopeBoundary = `## 写操作边界（只保留四条底线）

除下面四条之外，**一律自行判断推进**：读、枚举、探测、自建对象上的创建/修改/删除、状态机与金额类验证、并发验证，都不必请示、不必等批准、不必每轮重复确认授权。

四条底线（碰到任何一条 → 不执行，交 blocked 回执并在 asks 里写清要什么批准）：

1. **禁可用性打击**：不做 DoS / flood / 压测 / 资源耗尽，不得让目标中断、崩溃、重启，不得影响其业务与评分。
2. **禁销毁他人既有数据**：不删改真实业务记录与既有配置；不覆盖整仓配置（如 Node-RED 的 PUT /flow、NAS/中间件配置导入类）——这类接口没有"只加自己那一条"的语义，失败即生产事故。
3. **禁真实资金/真实人员的不可逆动作**：不退真实款、不触达真实人员（短信/邮件/电话/推送），不在真实账号上做不可回滚的状态变更。
4. **不越出授权范围**：范围外目标只记录不测试；范围本身不清时按低风险只读就近求证，不要在报告里含糊。

自建对象（本轮新建的测试账号/测试单/草稿）上的验证属于允许范围：用自己的测试标记命名、留台账、收工按台账逐条删，禁止用前缀/通配批删。
`
